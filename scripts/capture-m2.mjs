// Captures the M2 first-run storyboard: node scripts/capture-m2.mjs <url> <outDir>  (VW/VH env set the viewport)
import { chromium } from '@playwright/test';
const [url, out] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: Number(process.env.VW ?? 390), height: Number(process.env.VH ?? 844) }, deviceScaleFactor: 2 });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` });
await page.goto(url);
await page.getByRole('button', { name: /start your club/i }).click();
await page.waitForTimeout(700); await shot('01-intro1');
await page.locator('.intro__stage').click(); await page.waitForTimeout(700); await shot('02-intro2');
await page.locator('.intro__stage').click(); await page.waitForTimeout(900); await shot('03-intro3');
await page.locator('.intro__stage').click(); await page.waitForTimeout(700); await shot('04-intro4');
await page.getByRole('button', { name: /meet your first signing/i }).click();
await page.waitForTimeout(600); await shot('05-pack-sealed');
// drag the strip
const strip = page.locator('.pack__strip'); const box = await strip.boundingBox();
await page.mouse.move(box.x + 20, box.y + box.height / 2); await page.mouse.down();
await page.mouse.move(box.x + box.width * 0.4, box.y + box.height / 2, { steps: 6 });
await shot('06-pack-tearing');
await page.mouse.move(box.x + box.width * 0.9, box.y + box.height / 2, { steps: 6 }); await page.mouse.up();
await page.waitForTimeout(700); await shot('07-pack-emerging');
await page.waitForTimeout(1400); await shot('08-reveal');
await page.waitForTimeout(1500); await shot('09-reveal-done');
await page.getByRole('button', { name: /in the team/i }).click();
await page.waitForTimeout(600); await shot('10-lineup-coach');
await page.getByRole('button', { name: /put him there/i }).click();
await page.waitForTimeout(400); await shot('11-lineup-placed');
await page.getByRole('button', { name: /to the match/i }).click();
await page.waitForTimeout(500); await shot('12-lobby');
await page.getByRole('button', { name: /play match/i }).click();
await page.waitForSelector('.live__pitch canvas');
await page.locator('.live__speed').click();
try { await page.waitForSelector('.live__coach', { timeout: 40000 }); await page.waitForTimeout(300); await shot('13-live-tip'); await page.locator('.tchip').nth(1).click(); await page.waitForTimeout(500); await shot('14-live-after'); } catch { await shot('13-live-notip'); }
await page.getByRole('button', { name: /skip to ft/i }).click();
await page.getByRole('button', { name: /simulate the rest/i }).click();
await page.waitForSelector('.result__hero', { timeout: 20000 }); await page.waitForTimeout(1200);
await shot('15-result');
await page.locator('.result__upgrades').scrollIntoViewIfNeeded(); await page.waitForTimeout(300); await shot('16-result-upgrade');
await page.locator('.upgrade').first().getByRole('button', { name: /^train /i }).first().click();
await page.waitForTimeout(800); await shot('17-upgrade-done');
await page.getByRole('button', { name: /make it yours/i }).click();
await page.waitForTimeout(500); await shot('18-setup');
await page.locator('.setup__input').fill('Harbour Lights');
await page.locator('.setup__swatch').nth(1).click(); await page.getByRole('button', { name: 'Hoops' }).click();
await page.waitForTimeout(300); await shot('19-setup-filled');
await page.getByRole('button', { name: /that.s us/i }).click();
await page.waitForTimeout(800); await shot('20-hub');
await page.reload(); await page.waitForTimeout(1000); await shot('21-hub-reload');
await page.goto(url + '#/scout'); await page.waitForTimeout(600); await shot('22-scout');
console.log('ERRORS', JSON.stringify(errors));
await browser.close();
